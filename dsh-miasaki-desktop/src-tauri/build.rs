fn main() {
    tauri_build::build();
    gen_assets();
}

/// A 批：桌宠主题目录名判定——`mode` 或 `mode.<形象名>`（多形象平铺前缀键）。
/// mode 限纯小写字母（whale / kurumi / inverse）；形象名限 `[a-z0-9-]+`。
/// 与 `image::resolve_appearance_key` 的 charset 同口径（两侧不一致 = 扫到了却加载不到）。
fn is_mode_dir_name(n: &str) -> bool {
    let (base, variant) = match n.split_once('.') {
        Some((b, v)) => (b, Some(v)),
        None => (n, None),
    };
    if base.is_empty() || !base.chars().all(|c| c.is_ascii_lowercase()) {
        return false;
    }
    match variant {
        None => true,
        Some(v) => {
            !v.is_empty()
                && v.chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
        }
    }
}

/// 生成 src/assets.rs：把运行时素材（图标 + 桌宠帧）编译期内嵌进 EXE。
/// 磁盘 ui/（EXE 旁）仍作为覆盖层优先（dist 布局与开发覆盖不受影响），
/// 单文件拷贝 EXE 时自动回退内嵌。
fn gen_assets() {
    use std::fmt::Write;
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let ui_root = std::path::Path::new(&manifest).join("..").join("ui");
    let out = std::path::Path::new(&manifest).join("src").join("assets.rs");

    let mut files: Vec<String> = Vec::new();
    let add = |rel: &str, files: &mut Vec<String>| {
        if ui_root.join(rel).is_file() {
            files.push(rel.to_string());
        }
    };
    for name in ["app.png", "theme-pure.png", "theme-zafkiel.png", "theme-inverse.png"] {
        add(&format!("icons/{name}"), &mut files);
    }
    add("pets/frames.json", &mut files);
    add("pets/bubbles.png", &mut files);
    // R5(2026-09-16):审批气泡（240x84，含「拒绝 / 允许一次」两按钮）——
    // 帧高与 22 帧精灵表不同，故独立文件；此处显式登记（本函数是显式清单，不扫 pets/ 根）。
    add("pets/approval.png", &mut files);
    // R20-b(2026-10-17，design/2026-10-17-pet-fullscreen-sfx-sprint.md §3.2)：程序化音效
    // —— scripts/gen-sfx.mjs 构建期合成，一致性闸门见同脚本 --check 模式。
    // 显式登记而非扫目录：漏登记 = 运行时静默无声（与图集通道同族纪律）。
    // P0(2026-10-18，design/2026-10-18-pet-p0-interaction-emote.md §4)：+5 个互动音效。
    for name in [
        "jump", "land", "wave", "grab", "drop", "alert", "done", "tick", // R20-b 八件
        "pat", "chomp", "whoosh", "bounce", "yawn", //                     P0 五件
    ] {
        add(&format!("pets/sfx/{name}.wav"), &mut files);
    }
    // R20-c（2026-10-19 重做，design/2026-10-17-pet-fullscreen-sfx-sprint.md §4）：
    // 背景对比 halo 已改为**运行期程序化轮廓柔光**（从本帧角色 alpha 生成），
    // 不再有预渲染环 PNG ⇒ 这里没有素材要登记（`gen-halo.mjs` 已退役）。
    let pngs = |dir: &std::path::Path, prefix: &str, files: &mut Vec<String>| {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        let mut names: Vec<String> = rd
            .filter_map(|e| e.ok().map(|e| e.file_name().to_string_lossy().to_string()))
            .filter(|n| n.ends_with(".png"))
            .collect();
        names.sort();
        for n in names {
            files.push(format!("{prefix}/{n}"));
        }
    };
    // v5 L0-3(design/pet-v5-motion-plan.md) + A 批（2026-10-19，
    // design/2026-10-19-pet-a-appearance.md §3.5）：**图集行**与**立绘**按主题目录扫描。
    // 目录名 = mode 或 `mode.<形象名>`（A 批多形象：`whale.sakura/` 与 `whale/` 平级，
    // 自包含 frames/ + 可选 states/）。
    // 从显式两主题清单改为**动态发现**——新形象的素材零代码入链；「静默回落」风险
    // 由两侧管：loader 对缺失形象留痕（image::resolve_appearance_key 的 pet.log 行）
    // + check-pet-assets.mjs 做 frames.json ↔ 盘上文件双向校验（孤儿/缺失都报警）。
    // ⚠ 只扫 frames/ 与 states/ 两个子目录——`inverse/raw/`（抠图源立绘）等
    // 非运行时不进 EXE（2026-09-10 教训：素材源与派生物分属两链，不可互相顶替）。
    let mut modes: Vec<String> = match std::fs::read_dir(ui_root.join("pets")) {
        Ok(rd) => rd
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().to_string())
            .filter(|n| is_mode_dir_name(n))
            .collect(),
        Err(_) => Vec::new(),
    };
    modes.sort();
    for mode in &modes {
        for sub in ["frames", "states"] {
            pngs(
                &ui_root.join("pets").join(mode).join(sub),
                &format!("pets/{mode}/{sub}"),
                &mut files,
            );
        }
    }

    let mut s = String::new();
    s.push_str("// Generated by build.rs — runtime-embedded asset index (do not edit)\n");
    s.push_str("// 素材编译期内嵌；运行时磁盘 ui/（EXE 旁）优先，内嵌兜底（单文件拷贝可用）。\n");
    s.push_str("//\n");
    s.push_str("// 本文件是**生成物**，只留薄封装 —— 判定逻辑（来源解析 / 遮蔽报告）在手写的\n");
    s.push_str("// crate::asset_source 里，生成物不可单测，判据必须落在能跑测试的地方。\n");
    s.push_str("pub use crate::asset_source::Asset;\n");
    s.push_str("pub static ASSETS: &[Asset] = &[\n");
    for f in &files {
        let esc = f.replace('\\', "/");
        let _ = writeln!(
            s,
            "    Asset {{ path: \"{esc}\", data: include_bytes!(\"../../ui/{esc}\") }},"
        );
    }
    s.push_str("];\n");
    s.push_str("pub fn find(path: &str) -> Option<&'static Asset> {\n");
    s.push_str("    ASSETS.iter().find(|a| a.path == path)\n");
    s.push_str("}\n");
    s.push_str("/// 磁盘 ui/（EXE 旁）覆盖层目录；解析不出 EXE 位置时为 None。\n");
    s.push_str("pub fn ui_dir() -> Option<std::path::PathBuf> {\n");
    s.push_str("    std::env::current_exe().ok().and_then(|e| e.parent().map(|d| d.join(\"ui\")))\n");
    s.push_str("}\n");
    s.push_str("/// 磁盘 ui/ 优先（dist 布局 / 开发覆盖），内嵌兜底；来源判定见 crate::asset_source。\n");
    s.push_str("pub fn read(rel: &str) -> Option<Vec<u8>> {\n");
    s.push_str("    read_with_source(rel).map(|r| r.data)\n");
    s.push_str("}\n");
    s.push_str("/// 同 read()，但把**来源**一并带出（disk / embedded）—— 供诊断与启动摘要使用。\n");
    s.push_str("pub fn read_with_source(rel: &str) -> Option<crate::asset_source::Resolved> {\n");
    s.push_str("    let ui = ui_dir();\n");
    s.push_str("    let embedded = find(rel).map(|a| a.data);\n");
    s.push_str("    crate::asset_source::resolve(rel, ui.as_deref(), embedded, crate::asset_source::prefer_embedded_from_env())\n");
    s.push_str("}\n");
    s.push_str("/// 被磁盘覆盖层遮蔽的内嵌素材（内容不同者）—— 启动摘要与 E13 走查的机器判据。\n");
    s.push_str("pub fn disk_shadow_report() -> Vec<crate::asset_source::Shadow> {\n");
    s.push_str("    match ui_dir() {\n");
    s.push_str("        Some(d) => crate::asset_source::shadow_report(&d, ASSETS),\n");
    s.push_str("        None => Vec::new(),\n");
    s.push_str("    }\n");
    s.push_str("}\n");
    std::fs::write(&out, s).expect("write src/assets.rs");
    println!(
        "[build.rs] embedded assets: {} files → src/assets.rs",
        files.len()
    );
    println!("cargo:rerun-if-changed=../ui");
    println!("cargo:rerun-if-changed=build.rs");
}
